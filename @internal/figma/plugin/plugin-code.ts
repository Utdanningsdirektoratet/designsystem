import { readFileSync } from 'node:fs';
import path from 'node:path';

/**
 * The plugin's `main` file: the extractor followed by the plugin entry code. Figma loads a single
 * script, so the two are concatenated rather than imported.
 */
export function pluginCode(): string {
  const extractor = readFileSync(
    path.join(import.meta.dirname, '..', 'extract-snapshot.js'),
    'utf8',
  );
  const main = readFileSync(path.join(import.meta.dirname, 'main.js'), 'utf8');
  return `// Generated by @internal/figma/plugin/build.ts from extract-snapshot.js and plugin/main.js.\n${extractor}\n${main}`;
}
