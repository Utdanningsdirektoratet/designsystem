import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

/**
 * The fix plugin's `main` file: the plan (`plan.json` unless given) as the `PLAN` constant,
 * followed by `main.js`. Figma loads a single script, so the two are concatenated rather than
 * imported.
 */
export function fixPluginCode(
  plan = readFileSync(path.join(import.meta.dirname, 'plan.json'), 'utf8'),
): string {
  const main = readFileSync(path.join(import.meta.dirname, 'main.js'), 'utf8');
  return `// Generated by @internal/figma/fix-plugin/build.ts from plan.json and main.js.\nconst PLAN = ${plan.trim()};\n${main}`;
}

if (import.meta.main) {
  const outDir = path.join(import.meta.dirname, 'dist');
  mkdirSync(outDir, { recursive: true });
  writeFileSync(path.join(outDir, 'code.js'), fixPluginCode());
  console.log(
    `Wrote ${path.relative(process.cwd(), path.join(outDir, 'code.js'))}`,
  );
}
